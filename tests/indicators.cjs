const assert = require('node:assert/strict');
const fs = require('node:fs');
const { rsiArr, mean, apply } = require('../indicators-v1.js');
assert.deepEqual(rsiArr([], 14), []);
assert.deepEqual(rsiArr([1, 2, 1, 2, 1], 2), [null, null, 50, 75, 37.5]);
assert.equal(rsiArr(Array(40).fill(10), 14)[39], 50);
assert.equal(rsiArr(Array.from({length: 40}, (_, i) => i), 14)[39], 100);
assert.equal(rsiArr(Array.from({length: 40}, (_, i) => 40 - i), 14)[39], 0);
assert.deepEqual(rsiArr([1, 2], 14), [null, null]);
assert.deepEqual(rsiArr([1, 2, NaN, 1, 2, 3], 2), [null, null, null, null, null, 100]);
const wilder = [44.34,44.09,44.15,43.61,44.33,44.83,45.10,45.42,45.84,46.08,45.89,46.03,45.61,46.28,46.28,46,46.03,46.41,46.22,45.64];
assert.ok(Math.abs(rsiArr(wilder, 14)[14] - 70.4641350211) < 1e-8);
assert.ok(Math.abs(rsiArr(wilder, 14)[15] - 66.2496185536) < 1e-8);
assert.deepEqual(mean([null, null, 20, 40, 60], 2), [null, null, null, 30, 50]);
const game = fs.readFileSync(process.argv[2], 'utf8');
const patched = apply(game);
assert.notEqual(patched, game);
assert.equal(apply(patched), patched);
assert.equal(apply(game.replace('function rsiArr(v,p)', 'function futureRsi(v,p)')), game.replace('function rsiArr(v,p)', 'function futureRsi(v,p)'));
console.log('PASS RSI math: Wilder seed and smoothing, flat/rising/falling markets, warm-up, gaps, SMA, compatibility guards');
